function loadOpenApi() {
  const spec = JSON.parse(show(REPOS.backend, "openapi/openapi.json"));
  const ops = [];
  for (const [p, item] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(item)) {
      if (!["get", "post", "put", "patch", "delete"].includes(method)) continue;
      ops.push({ method: method.toUpperCase(), path: p, ...op });
    }
  }
  return { spec, ops };
}

function accessOf(op) {
  const schemes = new Set((op.security || []).flatMap((s) => Object.keys(s)));
  if (schemes.has("staffCookie")) return "staff";
  if (schemes.has("customerCookie") || schemes.has("bearerAuth")) return "user";
  return "public";
}
const ACCESS_LABEL = {
  public: '<span class="access access--public">Public</span>',
  user: '<span class="access access--user">Signed in</span>',
  staff: '<span class="access access--staff">Staff</span>',
};

function makeSchemaTools(spec) {
  const resolve = (s) => {
    let guard = 0;
    while (s && s.$ref && guard++ < 20) s = spec.components.schemas[s.$ref.split("/").pop()];
    return s || {};
  };
  const refName = (s) => (s && s.$ref ? s.$ref.split("/").pop() : null);

  const typeOf = (s, depth = 0) => {
    if (!s) return "any";
    const ref = refName(s);
    if (ref && depth > 0) return ref;
    s = resolve(s);
    if (s.const !== undefined) return JSON.stringify(s.const);
    if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
    const alt = s.anyOf || s.oneOf;
    if (alt) {
      const parts = alt.filter((a) => a.type !== "null").map((a) => typeOf(a, depth + 1));
      const nullable = alt.some((a) => a.type === "null");
      return [...new Set(parts)].join(" | ") + (nullable ? " | null" : "");
    }
    if (s.allOf) return s.allOf.map((a) => typeOf(a, depth + 1)).join(" & ");
    const t = Array.isArray(s.type) ? s.type.filter((x) => x !== "null").join(" | ") : s.type;
    if (t === "array") return `${typeOf(s.items, depth + 1)}[]`;
    if (t === "string" && s.format) return `string (${s.format})`;
    if (t === "object" && !s.properties && s.additionalProperties) return "object (map)";
    return t || "object";
  };

  const constraints = (s) => {
    s = resolve(s);
    const c = [];
    if (s.minLength !== undefined && s.maxLength !== undefined) c.push(`${s.minLength}–${s.maxLength} chars`);
    else if (s.maxLength !== undefined) c.push(`≤ ${s.maxLength} chars`);
    else if (s.minLength) c.push(`≥ ${s.minLength} chars`);
    if (s.minimum !== undefined && s.maximum !== undefined) c.push(`${s.minimum}–${s.maximum}`);
    else if (s.minimum !== undefined) c.push(`≥ ${s.minimum}`);
    else if (s.maximum !== undefined) c.push(`≤ ${s.maximum}`);
    if (s.exclusiveMinimum !== undefined) c.push(`> ${s.exclusiveMinimum}`);
    if (s.minItems !== undefined || s.maxItems !== undefined)
      c.push(`${s.minItems ?? 0}–${s.maxItems ?? "∞"} items`);
    if (s.pattern) c.push(`pattern ${code(s.pattern)}`);
    if (s.default !== undefined) c.push(`default ${code(JSON.stringify(s.default))}`);
    if (s.description) c.push(esc(s.description));
    return c.join("; ");
  };

  // Flattens an object schema into rows of (dotted name, type, required, notes).
  const fields = (schema, prefix = "", depth = 0, out = []) => {
    const s = resolve(schema);
    const variants = s.anyOf || s.oneOf;
    if (variants && !s.properties) {
      const objects = variants.map(resolve).filter((v) => v.properties);
      if (objects.length) {
        // A union of objects: list every field once, marking which are always present.
        const seen = new Map();
        for (const v of objects)
          for (const [k, p] of Object.entries(v.properties))
            if (!seen.has(k)) seen.set(k, { p, req: objects.every((o) => o.required?.includes(k)) });
        for (const [k, { p, req }] of seen) row(k, p, req);
        return out;
      }
    }
    if (!s.properties) return out;
    for (const [k, p] of Object.entries(s.properties)) row(k, p, (s.required || []).includes(k));
    return out;

    function row(k, p, req) {
      const name = prefix + k;
      out.push({ name, type: typeOf(p, 1), required: req, notes: constraints(p) });
      const inner = resolve(p);
      const child = inner.type === "array" ? resolve(inner.items) : inner;
      if (depth < 2 && child.properties && !refName(p) && !refName(inner.items))
        fields(child, `${name}${inner.type === "array" ? "[]" : ""}.`, depth + 1, out);
    }
  };

  return { resolve, refName, typeOf, constraints, fields };
}

const fieldTable = (rows) =>
  rows.length
    ? "| Field | Type | Required | Notes |\n| --- | --- | --- | --- |\n" +
      rows
        .map((r) => `| ${code(r.name)} | ${esc(r.type)} | ${r.required ? "Yes" : ""} | ${r.notes} |`)
        .join("\n") +
      "\n"
    : "";

const anchorOf = (op) => op.operationId.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const pathLabel = (p) => p.replace(/\{(\w+)\}/g, ":$1");

function renderApi() {
  const { spec, ops } = loadOpenApi();
  const tools = makeSchemaTools(spec);
  const tagDesc = Object.fromEntries((spec.tags || []).map((t) => [t.name, t.description || ""]));
  const used = new Set();
  const index = [];

  category("api", "API", 1, "Every endpoint of the backend, generated from its OpenAPI contract.");
  category("api/customer", "Public and customer API", 1);
  category("api/staff", "Staff API", 2);

  API_PAGES.forEach(([group, slug, title, tags], i) => {
    // An operation belongs to the page of its first tag (admin form routes are tagged ["admin", "forms"]).
    const pageOps = ops.filter((o) => tags.includes((o.tags || [])[0]));
    pageOps.forEach((o) => used.add(o));
    if (!pageOps.length) return;
    const intro = tags.map((t) => tagDesc[t]).filter(Boolean).join(" ");
    let md = `---\ntitle: ${yaml(title)}\nsidebar_position: ${i + 1}\ndescription: ${yaml(
      `${plural(pageOps.length, "endpoint")}: ${tags.join(", ")}.`,
    )}\n---\n\n# ${title}\n\n${banner(REPOS.backend)}\n`;
    if (intro) md += `${esc(intro)}\n\n`;
    md += `OpenAPI tags: ${tags.map(code).join(", ")}. ${plural(pageOps.length, "endpoint")}.\n\n`;
    md += "| | Endpoint | Access | What it does |\n| --- | --- | --- | --- |\n";
    for (const o of pageOps)
      md += `| <span class="method method--${o.method.toLowerCase()}">${o.method}</span> | [${code(
        pathLabel(o.path),
      )}](#${anchorOf(o)}) | ${ACCESS_LABEL[accessOf(o)]} | ${esc(o.summary)} |\n`;
    md += "\n";

    for (const o of pageOps) {
      md += `## ${o.method} ${esc(pathLabel(o.path))} \\{#${anchorOf(o)}\\}\n\n`;
      md += `${esc(o.summary)}\n\n`;
      md += `- **Access:** ${ACCESS_LABEL[accessOf(o)]}\n- **Operation id:** ${code(o.operationId)}\n`;
      const params = o.parameters || [];
      const headers = params.filter((p) => p.in === "header");
      for (const h of headers)
        md += `- **Header ${code(h.name)}**${h.required ? " (required)" : " (optional)"}: ${esc(h.description || "")}\n`;
      md += "\n";
      const pq = params.filter((p) => p.in === "path" || p.in === "query");
      if (pq.length) {
        md += "**Parameters**\n\n| Name | In | Type | Required | Notes |\n| --- | --- | --- | --- | --- |\n";
        for (const p of pq)
          md += `| ${code(p.name)} | ${p.in} | ${esc(tools.typeOf(p.schema, 1))} | ${p.required ? "Yes" : ""} | ${[
            esc(p.description || ""),
            tools.constraints(p.schema),
          ]
            .filter(Boolean)
            .join("; ")} |\n`;
        md += "\n";
      }
      const body = o.requestBody?.content?.["application/json"]?.schema;
      if (body) {
        const rows = tools.fields(body);
        md += `**Request body**${o.requestBody.required ? "" : " (optional)"}\n\n`;
        md += rows.length ? fieldTable(rows) : `${esc(tools.typeOf(body))}\n`;
        md += "\n";
      }
      const responses = Object.entries(o.responses || {});
      const ok = responses.filter(([s]) => /^2/.test(s));
      for (const [status, r] of ok) {
        const schema = r.content?.["application/json"]?.schema;
        md += `**Response ${status}**${r.description && r.description !== "OK" && r.description !== "Created" ? `: ${esc(r.description)}` : ""}\n\n`;
        if (!schema) {
          md += "No body.\n\n";
          continue;
        }
        const resolved = tools.resolve(schema);
        const data = resolved.properties?.data;
        const isList = data && tools.resolve(data).type === "array";
        const target = data ? (isList ? tools.resolve(data).items : data) : schema;
        const name = tools.refName(target);
        if (data) md += `Body: \`{ data${isList ? ": [...]" : ""}${resolved.properties.meta ? ", meta" : ""} }\`${name ? `, where ${isList ? "each item" : "`data`"} is **${name}**` : ""}.\n\n`;
        const rows = tools.fields(target);
        md += rows.length ? `<details>\n<summary>Fields</summary>\n\n${fieldTable(rows)}\n</details>\n\n` : "";
      }
      const errs = responses
        .filter(([s]) => !/^2/.test(s))
        .map(([s, r]) => {
          const codes = /Error codes: (.*)/.exec(r.description || "")?.[1];
          return `| ${s} | ${codes ? codes.split(/,\s*/).map(code).join(", ") : esc(r.description)} |`;
        });
      if (errs.length) md += `**Errors**\n\n| Status | Codes |\n| --- | --- |\n${errs.join("\n")}\n\n`;
    }
    write(`api/${group}/${slug}.md`, md);
    index.push({ group, slug, title, count: pageOps.length, tags });
  });

  const missed = ops.filter((o) => !used.has(o));
  if (missed.length) {
    console.warn(`! ${missed.length} operations have a tag not mapped in API_PAGES:`);
    for (const o of missed) console.warn(`  ${o.method} ${o.path} [${(o.tags || []).join(", ")}]`);
  }

  const byAccess = { public: 0, user: 0, staff: 0 };
  for (const o of ops) byAccess[accessOf(o)]++;
  return { total: ops.length, byAccess, pages: index, ops, spec };
}

