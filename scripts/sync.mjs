function tableOwners() {
  const files = lsTree(REPOS.backend, "src/modules").filter((f) => /\.table\.ts$/.test(f) && !f.includes("__tests__"));
  const owners = {};
  for (const f of files) {
    const mod = f.split("/")[2];
    const src = show(REPOS.backend, f);
    // The doc comment may not contain `*/`, so it can't reach back over an earlier table.
    const re = /(?:\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*)?export const (\w+) = pgTable\(\s*'([a-z0-9_]+)'/g;
    let m;
    while ((m = re.exec(src))) {
      const doc = (m[1] || "")
        .split("\n")
        .map((l) => l.replace(/^\s*\*\s?/, "").trim())
        .filter(Boolean)
        .join(" ");
      owners[m[3]] = { module: mod, file: f, doc };
    }
  }
  return owners;
}

function renderDataModel() {
  const metaDir = "src/db/migrations/meta";
  const snaps = lsTree(REPOS.backend, metaDir).filter((f) => /_snapshot\.json$/.test(f)).sort();
  const snap = JSON.parse(show(REPOS.backend, snaps.at(-1)));
  const migrations = lsTree(REPOS.backend, "src/db/migrations").filter((f) => /\.sql$/.test(f)).length;
  const owners = tableOwners();
  const tables = Object.values(snap.tables);
  const enums = Object.values(snap.enums);
  const byModule = {};
  for (const t of tables) (byModule[owners[t.name]?.module || "other"] ||= []).push(t);

  // No generated index: data-model/index.md is the category page.
  category("data-model", "Data model", 2);

  const modules = Object.keys(byModule).sort((a, b) => (MODULE_TITLES[a] || a).localeCompare(MODULE_TITLES[b] || b));
  modules.forEach((mod, i) => {
    const list = byModule[mod].sort((a, b) => a.name.localeCompare(b.name));
    const title = MODULE_TITLES[mod] || mod;
    let md = `---\ntitle: ${yaml(title)}\nsidebar_position: ${i + 2}\ndescription: ${yaml(
      `${plural(list.length, "table")} owned by the ${mod} module.`,
    )}\n---\n\n# ${title}\n\n${banner(REPOS.backend)}\n`;
    md += `${plural(list.length, "table")} owned by \`src/modules/${mod}\`: ${list.map((t) => `[${code(t.name)}](#${t.name.replace(/_/g, "-")})`).join(", ")}.\n\n`;

    // Relationship diagram: FKs from this module's tables, targets outside shown too.
    const edges = [];
    for (const t of list)
      for (const fk of Object.values(t.foreignKeys || {}))
        edges.push(`  ${fk.tableTo} ||--o{ ${t.name} : "${fk.columnsFrom.join(", ")}"`);
    // Big modules make an unreadable diagram; their FKs are in the column notes.
    const entityCount = new Set([...list.map((t) => t.name), ...edges.map((e) => e.trim().split(" ")[0])]).size;
    if (edges.length && entityCount <= 8) {
      const entities = list.filter((t) => !edges.some((e) => e.includes(` ${t.name} `))).map((t) => `  ${t.name}`);
      md += "```mermaid\nerDiagram\n" + [...new Set(edges)].join("\n") + (entities.length ? "\n" + entities.join("\n") : "") + "\n```\n\n";
    }

    for (const t of list) {
      const owner = owners[t.name];
      md += `## ${code(t.name)} \\{#${t.name.replace(/_/g, "-")}\\}\n\n`;
      if (owner?.doc) md += `${esc(owner.doc)}\n\n`;
      if (owner) md += `Defined in [${code(owner.file)}](${blob(REPOS.backend, owner.file)}).\n\n`;
      const fks = Object.values(t.foreignKeys || {});
      const fkOf = (col) => fks.find((f) => f.columnsFrom.length === 1 && f.columnsFrom[0] === col);
      const pk = new Set(Object.values(t.compositePrimaryKeys || {}).flatMap((p) => p.columns));
      md += "| Column | Type | Null | Default | Notes |\n| --- | --- | --- | --- | --- |\n";
      for (const c of Object.values(t.columns)) {
        const notes = [];
        if (c.primaryKey || pk.has(c.name)) notes.push("PK");
        if (c.isUnique) notes.push("unique");
        const fk = fkOf(c.name);
        if (fk) notes.push(`→ ${code(`${fk.tableTo}.${fk.columnsTo[0]}`)}${fk.onDelete && fk.onDelete !== "no action" ? ` (on delete ${fk.onDelete})` : ""}`);
        if (c.generated) notes.push(`generated: ${code(c.generated.as)}`);
        md += `| ${code(c.name)} | ${code(c.type)} | ${c.notNull ? "" : "yes"} | ${c.default !== undefined ? code(String(c.default)) : ""} | ${notes.join("; ")} |\n`;
      }
      md += "\n";
      const multiFks = fks.filter((f) => f.columnsFrom.length > 1);
      for (const f of multiFks)
        md += `- Foreign key (${f.columnsFrom.map(code).join(", ")}) → ${code(f.tableTo)} (${f.columnsTo.map(code).join(", ")})\n`;
      const uniques = Object.values(t.uniqueConstraints || {});
      const checks = Object.values(t.checkConstraints || {});
      const indexes = Object.values(t.indexes || {});
      if (uniques.length || checks.length || indexes.length || multiFks.length) {
        md += "<details>\n<summary>Constraints and indexes</summary>\n\n";
        for (const u of uniques) md += `- **Unique** ${code(u.name)}: (${u.columns.map(code).join(", ")})\n`;
        for (const c of checks) md += `- **Check** ${code(c.name)}: ${code(c.value.replace(/"/g, ""))}\n`;
        for (const ix of indexes) {
          const cols = ix.columns.map((c) => c.expression).join(", ");
          md += `- **${ix.isUnique ? "Unique index" : "Index"}** ${code(ix.name)} (${ix.method}): ${code(cols)}${ix.where ? ` where ${code(ix.where.replace(/"/g, ""))}` : ""}\n`;
        }
        md += "\n</details>\n\n";
      }
    }
    write(`data-model/${mod}.md`, md);
  });

  // Overview + enums
  let md = `---\ntitle: Overview\nsidebar_position: 1\ndescription: ${yaml(
    `${tables.length} tables and ${enums.length} enums across ${modules.length} modules.`,
  )}\n---\n\n# Data model\n\n${banner(REPOS.backend)}\n`;
  md += `PostgreSQL 17 with PostGIS. **${tables.length} tables** and **${enums.length} enums** in the \`public\` schema, built by ${migrations} migrations. Each table is defined next to the module that owns it (\`src/modules/<module>/*.table.ts\`) and re-exported from \`src/db/schema.ts\`.\n\n`;
  md += "| Module | Tables |\n| --- | --- |\n";
  for (const mod of modules)
    md += `| [${MODULE_TITLES[mod] || mod}](./${mod}.md) | ${byModule[mod].map((t) => code(t.name)).join(", ")} |\n`;
  md += `\n## Enums\n\nPostgres enum types, from \`src/db/enums.ts\`.\n\n| Enum | Values |\n| --- | --- |\n`;
  for (const e of enums.sort((a, b) => a.name.localeCompare(b.name)))
    md += `| ${code(e.name)} | ${e.values.map(code).join(", ")} |\n`;
  write("data-model/index.md", md);

  return { tables: tables.length, enums: enums.length, migrations, modules: modules.length };
}

// ─── 3. Error codes (src/lib/errors.ts) ─────────────────────────────────────

function renderErrors(ops) {
  const src = show(REPOS.backend, "src/lib/errors.ts");
  const block = src.slice(src.indexOf("ERROR_CATALOGUE = {"), src.indexOf("} as const", src.indexOf("ERROR_CATALOGUE = {")));
  const re = /^ {2}([A-Z0-9_]+): \{\s*status: (\d+),\s*message:\s*((?:'[^']*'|"[^"]*"|`[^`]*`)(?:\s*\+\s*(?:'[^']*'|"[^"]*"))*),?\s*\}/gm;
  const entries = [];
  let m;
  while ((m = re.exec(block))) {
    const message = [...m[3].matchAll(/'([^']*)'|"([^"]*)"|`([^`]*)`/g)].map((x) => x[1] ?? x[2] ?? x[3]).join("");
    entries.push({ code: m[1], status: Number(m[2]), message });
  }
  const declared = (block.match(/^ {2}[A-Z0-9_]+: \{/gm) || []).length;
  if (entries.length !== declared) console.warn(`! parsed ${entries.length} of ${declared} error codes`);

  const usage = {};
  for (const o of ops)
    for (const r of Object.values(o.responses || {}))
      for (const c of (/Error codes: (.*)/.exec(r.description || "")?.[1] || "").split(/,\s*/).filter(Boolean))
        (usage[c] ||= new Set()).add(o.operationId);

  let md = `---\ntitle: Error codes\nsidebar_position: 3\ndescription: ${yaml(`All ${entries.length} API error codes with their HTTP status.`)}\n---\n\n# Error codes\n\n${banner(REPOS.backend)}\n`;
  md += `Every API error has the same shape, and \`code\` is one of the ${entries.length} below. The message is the safe default shown to users; a route may replace it with a more specific one.\n\n`;
  md += '```json\n{ "error": { "code": "PLAN_REQUIRED", "message": "…", "requestId": "…", "details": {} } }\n```\n\n';
  md += `Source: [\`src/lib/errors.ts\`](${blob(REPOS.backend, "src/lib/errors.ts")}). "Endpoints" counts the routes whose contract lists the code.\n\n`;
  const statuses = [...new Set(entries.map((e) => e.status))].sort((a, b) => a - b);
  for (const s of statuses) {
    md += `## ${s}\n\n| Code | Default message | Endpoints |\n| --- | --- | --- |\n`;
    for (const e of entries.filter((x) => x.status === s))
      md += `| ${code(e.code)} | ${esc(e.message)} | ${usage[e.code]?.size || ""} |\n`;
    md += "\n";
  }
  write("error-codes.md", md);
  return entries.length;
}

// ─── 4. Settings (src/modules/settings/settings.keys.ts) ────────────────────

function renderSettings() {
  const src = show(REPOS.backend, "src/modules/settings/settings.keys.ts");
  const re = /^ {2}'([a-z0-9_.]+)': \{([\s\S]*?)^ {2}\},?$/gm;
  const defs = [];
  let m;
  while ((m = re.exec(src))) {
    const body = m[2];
    const def = /default:\s*([^,\n]+(?:\[[^\]]*\])?)/.exec(body)?.[1]?.trim();
    const desc = [...(/description:\s*((?:'[^']*'\s*\+?\s*)+)/.exec(body)?.[1] || "").matchAll(/'([^']*)'/g)]
      .map((x) => x[1])
      .join("");
    defs.push({ key: m[1], default: def, description: desc });
  }

  // A setting counts as read when its key appears in code outside the settings module, tests and seeds.
  const files = lsTree(REPOS.backend, "src").filter(
    (f) => f.endsWith(".ts") && !f.includes("__tests__") && !f.startsWith("src/modules/settings/") && !f.startsWith("src/db/"),
  );
  // Comment lines are dropped, so a key that is only mentioned in a comment doesn't count.
  const corpus = files
    .map((f) => show(REPOS.backend, f))
    .join("\n")
    .split("\n")
    .filter((l) => !/^\s*(\/\/|\/?\*)/.test(l))
    .join("\n");
  for (const d of defs) d.read = corpus.includes(`'${d.key}'`) || corpus.includes(`"${d.key}"`);

  let md = `---\ntitle: Settings\nsidebar_position: 4\ndescription: ${yaml(`All ${defs.length} runtime settings, their defaults and whether code reads them.`)}\n---\n\n# Settings\n\n${banner(REPOS.backend)}\n`;
  md += `Runtime settings live in the \`app_settings\` table, are validated by a Zod schema per key and cached in Redis. A super admin changes them through \`PATCH /v1/admin/settings/{key}\` (permission \`settings.manage\`), and every change is audited. For what each one means to users, see [Configurable rules](/product/platform/configurable-rules).\n\n`;
  md += `**Read by code** is checked by the sync: the key appears in a source file outside the settings module, tests and seeds. ${defs.filter((d) => !d.read).length} of ${defs.length} are not read anywhere yet, so changing them has no effect.\n\n`;
  const groups = [...new Set(defs.map((d) => d.key.split(".")[0]))];
  for (const g of groups) {
    md += `## ${g}\n\n| Key | Default | Read by code | Description |\n| --- | --- | --- | --- |\n`;
    for (const d of defs.filter((x) => x.key.startsWith(`${g}.`)))
      md += `| ${code(d.key)} | ${code(d.default)} | ${d.read ? "Yes" : "**No**"} | ${esc(d.description)} |\n`;
    md += "\n";
  }
  write("settings.md", md);
  return { total: defs.length, unread: defs.filter((d) => !d.read).map((d) => d.key) };
}

// ─── 5. Background jobs (src/lib/queue/jobs.ts + src/worker.ts) ─────────────

function describeCron(pattern, tz) {
  const [min, hour, dom, mon, dow] = pattern.split(" ");
  const zone = tz ? " IST" : " UTC";
  if (pattern === "* * * * *") return "Every minute";
  let m;
  if ((m = /^\*\/(\d+)$/.exec(min)) && hour === "*") return `Every ${m[1]} minutes`;
  if (/^\d+$/.test(min) && hour === "*") return min === "0" ? "Hourly, on the hour" : `Hourly at :${min.padStart(2, "0")}`;
  if (/^[\d,]+$/.test(min) && hour === "*") return `Every hour at ${min.split(",").map((x) => `:${x.padStart(2, "0")}`).join(" and ")}`;
  const time = `${hour.padStart(2, "0")}:${min.padStart(2, "0")}${zone}`;
  if (dom === "*" && mon === "*" && dow === "*") return `Daily at ${time}`;
  if (dom !== "*" && mon === "*") return `Monthly on day ${dom} at ${time}`;
  return `${code(pattern)}${zone}`;
}

function renderJobs() {
  const src = show(REPOS.backend, "src/lib/queue/jobs.ts");
  const worker = show(REPOS.backend, "src/worker.ts");
  const queues = {};
  for (const m of src.slice(src.indexOf("QUEUES = {"), src.indexOf("} as const", src.indexOf("QUEUES = {"))).matchAll(/'?([a-z-]+)'?: \{ concurrency: (\d+) \}/g))
    queues[m[1]] = Number(m[2]);

  const block = src.slice(src.indexOf("JOBS = {"), src.indexOf("} as const", src.indexOf("JOBS = {")));
  const jobs = [];
  const re = /^ {2}'([a-z0-9.-]+)': \{\n([\s\S]*?)^ {2}\},?$|^ {2}'([a-z0-9.-]+)': \{([^\n]*)\},?$/gm;
  let m;
  while ((m = re.exec(block))) {
    const name = m[1] || m[3];
    const body = m[2] || m[4];
    const queue = /queue: '([a-z-]+)'/.exec(body)[1];
    const before = block.slice(0, m.index).split("\n");
    const lines = [];
    for (let i = before.length - 2; i >= 0 && /^\s*\/\//.test(before[i]); i--) lines.unshift(before[i].replace(/^\s*\/\/\s?/, ""));
    const schedules = [];
    const sched = /schedules: \[([\s\S]*)\]/.exec(body)?.[1] || "";
    for (const [part] of sched.matchAll(/\{[^{}]*\}|every\(\d+\)|everyMinute|hourly|dailyIst\((?:at\([^)]*\))?\)/g)) {
      const key = /key: '([a-z-]+)'/.exec(part)?.[1];
      let s, x;
      if ((x = /pattern: '([^']+)'/.exec(part))) s = { pattern: x[1], tz: /tz: IST/.test(part) };
      else if (/everyMinute/.test(part)) s = { pattern: "* * * * *" };
      else if (/hourly/.test(part)) s = { pattern: "0 * * * *" };
      else if ((x = /every\((\d+)\)/.exec(part))) s = { pattern: `*/${x[1]} * * * *` };
      else if (/dailyIst\(\)/.test(part)) s = { pattern: "15 2 * * *", tz: true };
      else if ((x = /dailyIst\(at\((\d+)(?:,\s*(\d+))?\)\)/.exec(part))) s = { pattern: `${x[2] || 0} ${x[1]} * * *`, tz: true };
      if (s) schedules.push({ ...s, key });
    }
    jobs.push({ name, queue, schedules, comment: lines.join(" "), handled: worker.includes(`'${name}':`) });
  }

  let md = `---\ntitle: Background jobs\nsidebar_position: 5\ndescription: ${yaml(`${jobs.length} jobs on ${Object.keys(queues).length} queues; ${jobs.filter((j) => j.handled).length} have a handler.`)}\n---\n\n# Background jobs\n\n${banner(REPOS.backend)}\n`;
  md += `The job catalogue is [\`src/lib/queue/jobs.ts\`](${blob(REPOS.backend, "src/lib/queue/jobs.ts")}); handlers are wired in [\`src/worker.ts\`](${blob(REPOS.backend, "src/worker.ts")}). The worker registers a schedule only for jobs that have a handler, so **a job without a handler never runs**, and anything enqueued for it waits in Redis. See [Background jobs](../backend/background-jobs.md) for how the runtime works.\n\n`;
  md += `**${jobs.filter((j) => j.handled).length} of ${jobs.length}** jobs have a handler.\n\n## Queues\n\n| Queue | Concurrency | Jobs |\n| --- | --- | --- |\n`;
  for (const [q, c] of Object.entries(queues)) md += `| ${code(q)} | ${c} | ${jobs.filter((j) => j.queue === q).length} |\n`;
  md += `\n## Jobs\n\n| Job | Queue | Runs | Handler | Notes |\n| --- | --- | --- | --- | --- |\n`;
  for (const j of jobs)
    md += `| ${code(j.name)} | ${code(j.queue)} | ${j.schedules.length ? j.schedules.map((s) => `${describeCron(s.pattern, s.tz)}${s.key ? ` (${s.key})` : ""}`).join("<br/>") : "When enqueued"} | ${j.handled ? "Yes" : "**No**"} | ${esc(j.comment)} |\n`;
  write("jobs.md", md);
  return { total: jobs.length, handled: jobs.filter((j) => j.handled).length, unhandled: jobs.filter((j) => !j.handled).map((j) => j.name) };
}

// ─── 6. Website routes (bachelor-house-client app/) ─────────────────────────

function renderClientRoutes() {
  const files = lsTree(REPOS.client, "app");
  const pages = files.filter((f) => /\/page\.tsx?$/.test(f));
  const rows = pages.map((f) => {
    const dir = path.posix.dirname(f);
    const route =
      "/" +
      dir
        .split("/")
        .slice(1)
        .filter((s) => !/^\(.*\)$/.test(s))
        .join("/");
    const src = show(REPOS.client, f);
    const layoutFile = `${dir}/layout.tsx`;
    const layout = files.includes(layoutFile) ? show(REPOS.client, layoutFile) : "";
    const title = /title:\s*["'`]([^"'`]+)["'`]/.exec(src)?.[1] || /title:\s*["'`]([^"'`]+)["'`]/.exec(layout)?.[1] || "";
    const isClient = /^\s*["']use client["']/.test(src);
    const comps = [...src.matchAll(/from\s+["']@\/components\/([^"']+)["']/g)].map((x) => x[1]);
    const calls = /\bfetch\(|axios|\/v1\//.test(src);
    const group = /\/\((\w+)\)\//.exec(f)?.[1] || "";
    return { route: route === "/" ? "/" : route, file: f, title, isClient, comps, calls, group };
  });
  rows.sort((a, b) => a.route.localeCompare(b.route));
  const apiCalls = lsTree(REPOS.client, ".")
    .filter((f) => /\.(t|j)sx?$/.test(f))
    .filter((f) => /\bfetch\(|axios|\/v1\//.test(show(REPOS.client, f)));

  let md = `---\ntitle: Website routes\nsidebar_position: 6\ndescription: ${yaml(`${rows.length} pages of the Next.js website.`)}\n---\n\n# Website routes\n\n${banner(REPOS.client)}\n`;
  md += `Every \`page.tsx\` under \`app/\` of the Next.js App Router. Route groups in parentheses, such as \`(static)\`, don't appear in the URL. Titles come from the page's or layout's \`metadata\`. See [The website](../website/client.md) for how the app is put together.\n\n`;
  md += apiCalls.length
    ? `Files that call an API: ${apiCalls.map(code).join(", ")}.\n\n`
    : ":::caution[No API calls]\nNo file in the client calls the backend yet (`fetch`, `axios` or a `/v1/` path). Every page renders static or sample data.\n:::\n\n";
  md += "| Route | Title | Rendering | Main components |\n| --- | --- | --- | --- |\n";
  for (const r of rows)
    md += `| [${code(r.route)}](${blob(REPOS.client, r.file)}) | ${esc(r.title)} | ${r.isClient ? "Client" : "Server"} | ${r.comps.slice(0, 4).map((c) => code(c)).join(", ")}${r.comps.length > 4 ? ` +${r.comps.length - 4}` : ""} |\n`;
  write("client-routes.md", md);
  return { pages: rows.length, apiCalls: apiCalls.length };
}

