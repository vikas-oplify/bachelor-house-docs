#!/usr/bin/env node
// Regenerates the engineering reference (API, data model, error codes, settings,
// background jobs, website routes) from the BachelorHouse backend and client repos.
//
// Everything is read with `git show <ref>:<path>` / `git ls-tree <ref>`, so the
// output reflects the configured branch no matter what each repo has checked out.
// Hand-written pages are never touched; only docs/engineering/reference/** and
// src/data/sync.json are overwritten.
//
// Usage:  npm run sync                       (repos expected next to this project)
//         REPOS_DIR=/path npm run sync
//         BACKEND_REF=origin/main CLIENT_REF=origin/main npm run sync
//
// Fetch first (`git -C ../bachelor-house-backend fetch`) to pick up new commits.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DOCS_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPOS_DIR = process.env.REPOS_DIR || path.resolve(DOCS_ROOT, "..");
const REPOS = {
  backend: {
    dir: path.join(REPOS_DIR, "bachelor-house-backend"),
    ref: process.env.BACKEND_REF || "origin/chore/scaffold-from-reference",
    name: "bachelor-house-backend",
  },
  client: {
    dir: path.join(REPOS_DIR, "bachelor-house-client"),
    ref: process.env.CLIENT_REF || "main",
    name: "bachelor-house-client",
  },
};
const OUT = path.join(DOCS_ROOT, "docs", "engineering", "reference");
const GITHUB = "https://github.com/oplifyterminal";

// ─── git helpers ────────────────────────────────────────────────────────────

const git = (repo, args) =>
  execFileSync("git", ["-C", repo.dir, ...args], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
const show = (repo, file) => git(repo, ["show", `${repo.ref}:${file}`]);
const lsTree = (repo, dir) =>
  git(repo, ["ls-tree", "-r", "--name-only", repo.ref, "--", dir]).split("\n").filter(Boolean);
const headInfo = (repo) => {
  const [sha, date, subject] = git(repo, ["log", "-1", "--format=%h%x09%cI%x09%s", repo.ref])
    .trim()
    .split("\t");
  return { sha, date, subject, ref: repo.ref.replace(/^origin\//, "") };
};
const blob = (repo, file) =>
  `${GITHUB}/${repo.name}/blob/${repo.ref.replace(/^origin\//, "")}/${file}`;

// ─── output helpers ─────────────────────────────────────────────────────────

const written = new Set();
const write = (rel, content) => {
  const file = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  written.add(path.normalize(file));
};
const esc = (s) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\{/g, "&#123;")
    .replace(/\}/g, "&#125;")
    // ":word" would start an MDX text directive and vanish.
    .replace(/:(?=[A-Za-z])/g, "\\:")
    .replace(/\n+/g, " ");
const code = (s) => "`" + String(s).replace(/`/g, "'").replace(/\|/g, "\\|") + "`";
const yaml = (s) => JSON.stringify(String(s));
const plural = (n, word, many = `${word}s`) => `${n} ${n === 1 ? word : many}`;
const banner = (...repos) =>
  `:::info[Generated page]\n\nGenerated by \`npm run sync\` from ${repos
    .map((r) => `**${r.name}** \`${r.ref.replace(/^origin\//, "")}\``)
    .join(" and ")}. Don't edit it by hand: the next sync overwrites it.\n:::\n`;
const category = (dir, label, position, description) =>
  write(
    path.join(dir, "_category_.json"),
    JSON.stringify(
      {
        label,
        position,
        collapsed: true,
        link: description
          ? { type: "generated-index", slug: `/engineering/reference${dir ? `/${dir}` : ""}`, description }
          : undefined,
      },
      null,
      2,
    ) + "\n",
  );

